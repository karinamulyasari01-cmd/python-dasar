# Bab 6: Operator
a = 10
b = 3

print("Aritmatika")
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a // b)
print(a % b)
print(a ** b)

print("Perbandingan")
print(a == b)
print(a != b)
print(a > b)
print(a <= b)

print("Logika")
print(a > 5 and b < 5)
print(a > 5 or b > 5)
print(not (a > 5))

